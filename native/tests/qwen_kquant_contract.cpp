constexpr int kElements = 256;

bool decode_contract(
    const char* label,
    const std::uint8_t* packed,
    const float* expected,
    int blocks,
    float (*decode)(const std::uint8_t*, std::uint64_t)
) {
    for (int index = 0; index < blocks * kElements; ++index) {
        const float actual = decode(packed, static_cast<std::uint64_t>(index));
        // The reference recombines the same integers in f32, so the decoders
        // have to agree bit for bit rather than merely closely.
        if (actual != expected[index]) {
            std::printf(
                "%s element %d: expected %.9e, got %.9e\n",
                label, index, expected[index], actual
            );
            return false;
        }
    }
    return true;
}

// The runtime dots whole super-blocks so it can hoist each group's scale out
// of the inner loop. Check that reordering against a plain sum over the
// reference values, one row at a time.
bool dot_contract(
    const char* label,
    const std::uint8_t* packed,
    const float* expected,
    int blocks,
    float (*dot)(const std::uint8_t*, const float*, int, std::uint64_t)
) {
    float input[kElements];
    for (int i = 0; i < kElements; ++i)
        input[i] = std::sin(static_cast<float>(i) * 0.031f) * 0.8f;
    for (int row = 0; row < blocks; ++row) {
        double reference = 0.0;
        for (int i = 0; i < kElements; ++i)
            reference += static_cast<double>(expected[row * kElements + i]) * input[i];
        const float actual =
            dot(packed, input, kElements, static_cast<std::uint64_t>(row));
        const double tolerance = 1.0e-5 * std::max(1.0, std::fabs(reference));
        if (std::fabs(reference - actual) > tolerance) {
            std::printf(
                "%s row %d dot: expected %.9e, got %.9e\n",
                label, row, reference, actual
            );
            return false;
        }
    }
    return true;
}

// The SIMD kernels must agree with the scalar decode on the same real blocks.
// They are exercised through the public entry points, which is also what pins
// the type dispatch: an unlisted type silently decodes as Q8_0 there.
bool simd_contract(
    const char* label,
    std::uint32_t type,
    const std::uint8_t* packed,
    const float* expected,
    int blocks,
    bool avx512
) {
    float input[kElements];
    for (int i = 0; i < kElements; ++i)
        input[i] = std::cos(static_cast<float>(i) * 0.017f) * 0.6f;
    std::vector<float> decoded(kElements);
    for (int row = 0; row < blocks; ++row) {
        double reference = 0.0;
        for (int i = 0; i < kElements; ++i)
            reference += static_cast<double>(expected[row * kElements + i]) * input[i];
        const float avx2 = qwen_quant_dot_avx2(
            packed, type, input, kElements, static_cast<std::uint64_t>(row));
        if (std::fabs(reference - avx2) > 1.0e-4 * std::max(1.0, std::fabs(reference))) {
            std::printf("%s row %d AVX2 dot: expected %.9e, got %.9e\n",
                        label, row, reference, avx2);
            return false;
        }
        qwen_dequant_row_avx2(
            packed, type, kElements, static_cast<std::uint64_t>(row), decoded.data());
        for (int i = 0; i < kElements; ++i) {
            if (decoded[i] != expected[row * kElements + i]) {
                std::printf("%s row %d element %d AVX2 dequant: expected %.9e, got %.9e\n",
                            label, row, i, expected[row * kElements + i], decoded[i]);
                return false;
            }
        }
        if (!avx512) continue;
        const float wide = qwen_quant_dot_avx512(
            packed, type, input, kElements, static_cast<std::uint64_t>(row));
        if (std::fabs(reference - wide) > 1.0e-4 * std::max(1.0, std::fabs(reference))) {
            std::printf("%s row %d AVX-512 dot: expected %.9e, got %.9e\n",
                        label, row, reference, wide);
            return false;
        }
        qwen_dequant_row_avx512(
            packed, type, kElements, static_cast<std::uint64_t>(row), decoded.data());
        for (int i = 0; i < kElements; ++i) {
            if (decoded[i] != expected[row * kElements + i]) {
                std::printf("%s row %d element %d AVX-512 dequant: expected %.9e, got %.9e\n",
                            label, row, i, expected[row * kElements + i], decoded[i]);
                return false;
            }
        }
    }
    return true;
}

